    private String playlistUrl() throws Exception { String token=tokenInput.getText().toString().trim(); if(token.isEmpty()) throw new IOException("أدخل رمز playlist token الموجود في إعدادات وربط اللوحة."); return BASE+"/playlist.php?token="+URLEncoder.encode(token,"UTF-8"); }
    private String read(HttpURLConnection c)throws Exception{
        int code=c.getResponseCode();InputStream in=(code>=200&&code<300)?c.getInputStream():c.getErrorStream();ByteArrayOutputStream out=new ByteArrayOutputStream();
        if(in!=null){byte[] b=new byte[8192];int n;while((n=in.read(b))!=-1)out.write(b,0,n);in.close();}
        String body=out.toString("UTF-8").trim();String type=c.getContentType()==null?"":c.getContentType().toLowerCase(Locale.ROOT);
        if(code<200||code>=300)throw new IOException("HTTP "+code+" — "+body.substring(0,Math.min(180,body.length())));
        if(body.isEmpty())throw new IOException("السيرفر أعاد استجابة فارغة.");
        if(body.startsWith("<")||type.contains("text/html"))throw new IOException("الموقع أعاد صفحة HTML بدل API. تحقق من PHP وplayer_api.php على الاستضافة.");
        return body;
    }
    private String fetchText(String url)throws Exception{
        HttpURLConnection c=(HttpURLConnection)new URL(url).openConnection();
        c.setConnectTimeout(25000);c.setReadTimeout(90000);c.setInstanceFollowRedirects(true);
        c.setRequestProperty("Accept","audio/x-mpegurl,application/vnd.apple.mpegurl,text/plain,*/*");
        c.setRequestProperty("User-Agent","Mozilla/5.0 (Linux; Android 14) AppleWebKit/537.36 Chrome/130 Mobile Safari/537.36");
        try{
            int code=c.getResponseCode();InputStream in=(code>=200&&code<300)?c.getInputStream():c.getErrorStream();
            ByteArrayOutputStream out=new ByteArrayOutputStream();if(in!=null){byte[] b=new byte[16384];int n;while((n=in.read(b))!=-1)out.write(b,0,n);in.close();}
            String body=out.toString("UTF-8").trim();
            if(code<200||code>=300)throw new IOException("HTTP "+code+": "+body.substring(0,Math.min(180,body.length())));
            if(body.isEmpty())throw new IOException("رابط القائمة أعاد محتوى فارغاً.");
            if(body.startsWith("<"))throw new IOException("playlist.php أعاد صفحة HTML وليست قائمة M3U. تأكد أن الرابط يعمل وأن الرمز صحيح.");
            if(!body.contains("#EXTINF"))throw new IOException("الاستجابة ليست ملف M3U صالحاً (لم يتم العثور على #EXTINF).");
            return body;
        }finally{c.disconnect();}
    }
    private String attr(String line,String key){
        int p=line.indexOf(key+"=\"");
        if(p<0)return "";
        int a=p+key.length()+2;
        int b=line.indexOf("\"",a);
        return b>a?line.substring(a,b):"";
    }
    private String cleanName(String s){
        return s.replaceAll("(?i)\\s*S[0-9]{1,2}E[0-9]{1,3}.*$","")
                .replaceAll("(?i)\\s*[0-9]{1,2}x[0-9]{1,3}.*$","").trim();
    }
    private boolean isSeries(String name,String group,String url){
        String z=(name+" "+group+" "+url).toLowerCase(Locale.ROOT);
        return z.matches("(?s).*\\b(s[0-9]{1,2}e[0-9]{1,3}|[0-9]{1,2}x[0-9]{1,3})\\b.*")
            ||z.contains("series")||z.contains("episode")||z.contains("مسلسل")||z.contains("حلقات")||z.contains("مسلسلات");
    }
    private boolean isMovie(String name,String group,String url){
        String z=(name+" "+group+" "+url).toLowerCase(Locale.ROOT);
        return z.contains("movie")||z.contains("movies")||z.contains("film")||z.contains("cinema")||z.contains("أفلام")||z.contains("فيلم");
    }
    private List<Item> parsePlaylist(String m3u,String key){
        List<Item> out=new ArrayList<>();String[] lines=m3u.split("\\r?\\n");String title=null,group="عام",logo="";
        for(String raw:lines){String line=raw.trim();if(line.startsWith("#EXTINF")){
            int comma=line.lastIndexOf(',');title=comma>=0?line.substring(comma+1).trim():"بدون اسم";
            group=attr(line,"group-title");if(group.isEmpty())group="عام";logo=attr(line,"tvg-logo");
        }else if(!line.isEmpty()&&!line.startsWith("#")&&title!=null){
            boolean series=isSeries(title,group,line),movie=isMovie(title,group,line);
            boolean match=key.equals("live")?(!series&&!movie):key.equals("movies")?(!series&&movie):series;
            if(match){Item x=new Item(new JSONObject(),"");x.id=String.valueOf(out.size());x.name=title;x.category=group;x.url=line;x.logo=logo;x.extension="";x.seriesName=cleanName(title);out.add(x);}
            title=null;group="عام";logo="";
        }}
        return out;
    }
    private void load(String key){
        section=key;showingEpisodes=false;heading.setText(key.equals("live")?"القنوات المباشرة":key.equals("movies")?"الأفلام":"المسلسلات");status.setText("جارٍ تنزيل قائمة المحتوى من playlist.php...");list.removeAllViews();
        io.execute(()->{try{
            String m3u=fetchText(playlistUrl());List<Item> result=parsePlaylist(m3u,key);
            runOnUiThread(()->{data.clear();data.addAll(result);render();status.setText("تم استيراد "+result.size()+" عنصر من قائمة السيرفر. إجمالي حجم القائمة: "+m3u.length()+" حرف.");});
        }catch(Exception e){runOnUiThread(()->status.setText("فشل الاتصال: "+friendly(e)));}});
    }
    private void loadEpisodes(Item series){
        List<Item> episodes=new ArrayList<>();for(Item x:data)if(x.seriesName.equals(series.seriesName))episodes.add(x);
        if(episodes.size()<=1){status.setText("لم أجد حلقات أخرى مرتبطة بهذا المسلسل في قائمة M3U.");return;}
        data.clear();data.addAll(episodes);showingEpisodes=true;heading.setText(series.seriesName+" — الحلقات");render();status.setText("تم العثور على "+episodes.size()+" حلقة.");
    }
    private void render(){
        if(list==null)return;list.removeAllViews();String q=search.getText().toString().trim().toLowerCase(Locale.ROOT);int shown=0;
        for(Item x:new ArrayList<>(data)){if(!q.isEmpty()&&!x.name.toLowerCase(Locale.ROOT).contains(q))continue;shown++;
            LinearLayout card=new LinearLayout(this);card.setOrientation(1);card.setPadding(dp(13),dp(9),dp(13),dp(9));card.setBackground(shape(CARD));list.addView(card,params(-2,8));
            card.addView(text(x.name,16,FG,true));card.addView(text(x.category,12,MUTED,false));
            boolean series=section.equals("series")&&!showingEpisodes;Button action=button(series?"عرض الحلقات":"تشغيل  ▶",true);card.addView(action,params(44,8));
            action.setOnClickListener(v->{if(series)loadEpisodes(x);else play(x);});
        }
        count.setText("العناصر: "+shown);if(shown==0)list.addView(text("لا توجد نتائج.",14,MUTED,false));
    }
    private void loadEpisodes(Item series){
        status.setText("جارٍ تحميل حلقات "+series.name+"...");
        io.execute(()->{try{
            JSONObject info=getObject("get_series_info","series_id="+URLEncoder.encode(series.id,"UTF-8"));
            JSONObject groups=info.optJSONObject("episodes");if(groups==null)throw new IOException("السيرفر لم يُرجع قائمة حلقات لهذا المسلسل.");
            List<Item> episodes=new ArrayList<>();Iterator<String> seasons=groups.keys();
            while(seasons.hasNext()){String season=seasons.next();JSONArray a=groups.optJSONArray(season);if(a==null)continue;for(int i=0;i<a.length();i++){JSONObject ep=a.getJSONObject(i);Item item=new Item(ep,"episode");item.seriesId=series.id;item.seriesName=series.name;item.season=ep.optInt("season",Integer.parseInt(season));episodes.add(item);}}
            episodes.sort(Comparator.comparingInt((Item x)->x.season).thenComparingInt(x->x.episode));
            runOnUiThread(()->{data.clear();data.addAll(episodes);allEpisodes.clear();allEpisodes.addAll(episodes);showingEpisodes=true;heading.setText(series.name+" — الحلقات");render();status.setText("تم تحميل "+episodes.size()+" حلقة.");});
        }catch(Exception e){runOnUiThread(()->status.setText("فشل تحميل الحلقات: "+friendly(e)));}});
    }
    private void play(Item x){
        String url=x.url;
        if(url==null||!(url.startsWith("https://")||url.startsWith("http://"))){status.setText("رابط البث غير صالح.");return;}
        try{if(player==null){player=new ExoPlayer.Builder(this).build();playerView.setPlayer(player);player.addListener(new Player.Listener(){@Override public void onPlaybackStateChanged(int s){if(s==Player.STATE_BUFFERING)status.setText("جارٍ تحميل البث...");if(s==Player.STATE_READY)status.setText("يعمل الآن.");}@Override public void onPlayerError(PlaybackException e){status.setText("خطأ تشغيل: "+e.getMessage());}});}
            playerBox.setVisibility(View.VISIBLE);MediaItem.Builder item=new MediaItem.Builder().setUri(Uri.parse(url));String path=Uri.parse(url).getPath();if(path!=null&&path.toLowerCase(Locale.ROOT).endsWith(".m3u8"))item.setMimeType(MimeTypes.APPLICATION_M3U8);player.setMediaItem(item.build());player.prepare();player.play();status.setText("جارٍ بدء التشغيل...");
        }catch(Exception e){status.setText("تعذّر تشغيل المحتوى: "+e.getMessage());}
    }
    private void stopPlayer(){if(player!=null){player.stop();player.release();player=null;}playerBox.setVisibility(View.GONE);}
    private String friendly(Exception e){String m=e.getMessage()==null?"خطأ غير معروف":e.getMessage();if(m.contains("UnknownHost")||m.contains("resolve"))return"تعذّر الوصول إلى الدومين. تحقق من الإنترنت واسم الموقع.";if(m.contains("401")||m.contains("403"))return"السيرفر رفض رمز القائمة. أنشئ رمز Playlist جديداً من إعدادات وربط اللوحة.";return m;}
    @Override protected void onDestroy(){stopPlayer();io.shutdownNow();super.onDestroy();}
